"""Declarative base and shared column conventions.

Every model in the service inherits from `Base`. Alembic's autogenerate
reads `Base.metadata`, so a model that isn't imported before a migration is
generated is a model Alembic won't see — `db/models/__init__.py` exists to
import them all in one place.
"""

from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Explicit, deterministic constraint names. Without this, Postgres invents
# names, and a migration that needs to drop a constraint has nothing stable
# to reference — autogenerated downgrades break on exactly this.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    def __repr__(self) -> str:
        pk: Any = getattr(self, "id", None)
        return f"<{type(self).__name__} id={pk!r}>"


class TimestampMixin:
    """created_at / updated_at maintained by the database, not the app.

    Server-side defaults mean rows written by a migration, a backfill script,
    or psql get correct timestamps too — not just rows written through the ORM.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
