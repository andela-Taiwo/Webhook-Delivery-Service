"""Alembic environment — async-aware, credentials sourced from Settings.

The database URL is read from configuration at runtime (never from
alembic.ini, which is committed). Precedence: an explicit
`sqlalchemy.url` set programmatically by `db/migrations.py` (tests point it
at a container), otherwise `settings.database_url` from the environment.
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from webhook_service.core.config import settings

# Importing the model registry populates Base.metadata. Without this,
# autogenerate sees no tables and cheerfully writes a migration that drops
# the entire schema.
import webhook_service.db.models  # noqa: F401
from webhook_service.db.base import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

if not config.get_main_option("sqlalchemy.url", None):
    config.set_main_option("sqlalchemy.url", settings.database_url)

target_metadata = Base.metadata


def _include_object(obj: object, name: str | None, type_: str, *_args: object) -> bool:
    """Keep test scratch tables out of autogenerated migrations."""
    if type_ == "table" and name is not None and name.startswith("_"):
        return False
    return True


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting — for DBA review of a release."""
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        # Without these, a changed column type or default is silently missed
        # by autogenerate and drifts between models and database forever.
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    """Run migrations, reusing a caller-supplied connection when present.

    `db/migrations.py` passes an existing connection via attributes so
    programmatic callers (tests, the app's startup check) don't open a second
    engine just to migrate.
    """
    connectable = config.attributes.get("connection", None)
    if connectable is not None:
        do_run_migrations(connectable)
    else:
        asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
